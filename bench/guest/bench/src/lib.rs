//! Arm C's guest: the workload, built through the `blitz` host imports.
//!
//! There is no JavaScript in this path and no generated glue. The module is
//! compiled to `wasm32-unknown-unknown`, instantiated by wasmi, and the tree it
//! produces is a real `blitz-dom` document.
//!
//! Two workloads live here.
//!
//! **The upstream rows** (`prepare`, `create_rows`, `update_every_tenth`) are
//! the licensed, cited baseline taken from js-framework-benchmark. They are
//! kept unchanged so the paper's original table stays reproducible.
//!
//! **The sweep** (`sweep_prepare`, `sweep_build`, `sweep_settle`) executes a
//! program generated by [`workload::scenario`]. The guest links that crate, so
//! the program is not transcribed and cannot drift from the definition the
//! harness swept.
//!
//! # What is inside the measured window and what is not
//!
//! `sweep_prepare` expands the configuration into a `Vec<Step>` and allocates
//! every string it will ever send. That is guest-side work, it is not the
//! boundary, and doing it inside the timed call would put a string formatter
//! into a measurement of a binding. Only `sweep_build` is measured, and all it
//! does is walk a prepared list issuing host calls.

use std::cell::{Cell, RefCell};

use blitz_wasm_guest::{Element, Error, Node, text};
use workload::scenario::{Config, MOUNT, Program, Step, TAG};
use workload::{Store, UPDATE_STRIDE, UPDATE_SUFFIX};

// ---------------------------------------------------------------------------
// The upstream row workload, unchanged.
// ---------------------------------------------------------------------------

/// Everything the row workload remembers between calls.
///
/// The label anchors are the interesting part. A handle is stable for the life
/// of the instance, so a guest that keeps one can return to that node later
/// without searching for it, which is what a framework's reactive graph holds.
/// `partial-update` is a thousand writes through a thousand remembered handles
/// and involves no traversal at all.
struct RowState {
    tbody: Option<Node>,
    /// One entry per row: the `<a>` holding the label, and the label text.
    labels: Vec<(Node, String)>,
    store: Store,
}

thread_local! {
    static ROWS: RefCell<RowState> = RefCell::new(RowState {
        tbody: None,
        labels: Vec::new(),
        store: Store::new(),
    });
}

/// Build the empty table and reset the generator. Not part of either measured
/// operation: `create-1000` is defined as building rows *into an empty table*,
/// so the table itself is setup.
#[unsafe(no_mangle)]
pub extern "C" fn prepare() -> i32 {
    status(build_table())
}

fn build_table() -> Result<(), Error> {
    let table = Element::new("table")?;
    let tbody = Element::new("tbody")?;
    table.append(tbody.node())?;
    Node::mount().append(table.node())?;

    ROWS.with(|state| {
        let mut state = state.borrow_mut();
        state.tbody = Some(tbody.node());
        state.labels.clear();
        state.store = Store::new();
    });
    Ok(())
}

/// Append `count` rows. `create-1000` calls this with 1,000.
#[unsafe(no_mangle)]
pub extern "C" fn create_rows(count: i32) -> i32 {
    if count < 0 {
        return -5;
    }
    status(append_rows(count as usize))
}

/// The row, exactly as the upstream workload specifies it:
///
/// ```html
/// <tr>
///   <td class='col-md-1'>{id}</td>
///   <td class='col-md-4'><a>{label}</a></td>
///   <td class='col-md-1'><a><span class='glyphicon glyphicon-remove'
///       aria-hidden='true'></span></a></td>
///   <td class='col-md-6'></td>
/// </tr>
/// ```
fn append_rows(count: usize) -> Result<(), Error> {
    ROWS.with(|state| {
        let mut state = state.borrow_mut();
        let Some(tbody) = state.tbody else {
            return Err(Error(-1)); // ERR_BAD_HANDLE: `prepare` was never called.
        };

        for _ in 0..count {
            let row = state.store.next_row();

            let tr = Element::new("tr")?;

            let id_cell = Element::new("td")?;
            id_cell.set_attribute("class", "col-md-1")?;
            id_cell.append(text(&row.id.to_string())?)?;
            tr.append(id_cell.node())?;

            let label_cell = Element::new("td")?;
            label_cell.set_attribute("class", "col-md-4")?;
            let anchor = Element::new("a")?;
            anchor.append(text(&row.label)?)?;
            label_cell.append(anchor.node())?;
            tr.append(label_cell.node())?;

            let remove_cell = Element::new("td")?;
            remove_cell.set_attribute("class", "col-md-1")?;
            let remove_anchor = Element::new("a")?;
            let glyph = Element::new("span")?;
            glyph.set_attribute("class", "glyphicon glyphicon-remove")?;
            glyph.set_attribute("aria-hidden", "true")?;
            remove_anchor.append(glyph.node())?;
            remove_cell.append(remove_anchor.node())?;
            tr.append(remove_cell.node())?;

            let spacer = Element::new("td")?;
            spacer.set_attribute("class", "col-md-6")?;
            tr.append(spacer.node())?;

            tbody.append(tr.node())?;
            state.labels.push((anchor.node(), row.label));
        }
        Ok(())
    })
    .map(|()| ())
}

/// `partial-update`: append the suffix to every tenth row's label.
#[unsafe(no_mangle)]
pub extern "C" fn update_every_tenth() -> i32 {
    status(ROWS.with(|state| {
        let mut state = state.borrow_mut();
        let mut index = 0;
        while index < state.labels.len() {
            let (node, label) = &mut state.labels[index];
            label.push_str(UPDATE_SUFFIX);
            node.set_text(label)?;
            index += UPDATE_STRIDE;
        }
        Ok(())
    }))
}

// ---------------------------------------------------------------------------
// The sweep.
// ---------------------------------------------------------------------------

thread_local! {
    /// The expanded program, built in `sweep_prepare` and walked in
    /// `sweep_build`.
    static PROGRAM: RefCell<Vec<Step>> = const { RefCell::new(Vec::new()) };
    /// Handles to the elements, indexed as the program indexes them.
    ///
    /// `Element` rather than `Node`: the bindings model an element as a node
    /// plus attribute operations and offer no way back down from one to the
    /// other, so keeping the wider type and calling `.node()` where a plain
    /// node is wanted is the only direction that works.
    static NODES: RefCell<Vec<Element>> = const { RefCell::new(Vec::new()) };
    /// The listeners, kept alive. Dropping a `Listener` would deregister it,
    /// so a guest that attached a thousand and held none would dispatch none.
    static LISTENERS: RefCell<Vec<blitz_wasm_guest::Listener>> = const {
        RefCell::new(Vec::new())
    };
    /// How many times a handler has run.
    ///
    /// Deliberately the only thing a handler does. A handler that also touched
    /// the DOM would fold a `set_text` into every dispatch and the event axis
    /// would measure text writing, when the question it exists to answer is
    /// what the dispatch path itself costs.
    static FIRED: Cell<u32> = const { Cell::new(0) };
    /// Empty text nodes, one per element, created during the build so that the
    /// text phase rewrites a text node in place rather than replacing an
    /// element's children and destroying the tree the shape axis just built.
    static TEXTS: RefCell<Vec<Node>> = const { RefCell::new(Vec::new()) };
    /// Every distinct class value, built once in `sweep_prepare`.
    ///
    /// A lookup, not a format. Rendering the value per step put a string
    /// formatter inside the measured window, and the short-to-long contrast
    /// then moved by the same amount whether five hundred or a hundred and
    /// thirty thousand extra bytes crossed the boundary.
    static VOCABULARY: RefCell<Vec<String>> = const { RefCell::new(Vec::new()) };
    /// Kept only so a reader of this file can see what was configured; the
    /// program itself carries everything execution needs.
    static CONFIG: Cell<Option<Config>> = const { Cell::new(None) };
}

/// Expand the configuration and reset. Untimed and uncounted.
#[unsafe(no_mangle)]
pub extern "C" fn sweep_prepare(
    vocabulary_kind: i32,
    vocabulary_size: i32,
    names: i32,
    chattiness: i32,
    shape: i32,
    elements: i32,
    listeners: i32,
) -> i32 {
    let config = Config::from_ints([
        vocabulary_kind,
        vocabulary_size,
        names,
        chattiness,
        shape,
        elements,
        listeners,
    ]);
    let program = Program::build(config);

    CONFIG.with(|slot| slot.set(Some(config)));
    VOCABULARY.with(|slot| *slot.borrow_mut() = program.vocabulary);
    PROGRAM.with(|slot| *slot.borrow_mut() = program.steps);
    NODES.with(|slot| slot.borrow_mut().clear());
    TEXTS.with(|slot| slot.borrow_mut().clear());
    LISTENERS.with(|slot| slot.borrow_mut().clear());
    FIRED.with(|slot| slot.set(0));
    0
}

/// Execute the program. **This is the measured operation.**
#[unsafe(no_mangle)]
pub extern "C" fn sweep_build() -> i32 {
    status(run_program())
}

fn run_program() -> Result<(), Error> {
    let Some(config) = CONFIG.with(|slot| slot.get()) else {
        return Err(Error(-1)); // ERR_BAD_HANDLE: `sweep_prepare` was never called.
    };

    PROGRAM.with(|program| {
        let program = program.borrow();
        VOCABULARY.with(|vocabulary| {
            let vocabulary = vocabulary.borrow();
            NODES.with(|nodes| {
                let mut nodes = nodes.borrow_mut();
                TEXTS.with(|texts| {
                    let mut texts = texts.borrow_mut();
                    nodes.reserve(config.elements);
                    texts.reserve(config.elements);

                    for step in program.iter() {
                        match step {
                            Step::Create => {
                                nodes.push(Element::new(TAG)?);
                            }
                            Step::SetClass(index) => {
                                // A lookup. `set_attribute` interns, and the
                                // guest bindings memoise, so a value seen
                                // before crosses nothing at all.
                                let element = *nodes.last().ok_or(Error(-1))?;
                                let value = vocabulary.get(*index).ok_or(Error(-5))?;
                                element.set_attribute("class", value)?;
                            }
                            Step::CreateText => {
                                // Empty: zero bytes across the boundary. The
                                // text phase fills it in place later.
                                texts.push(text("")?);
                            }
                            Step::AppendTextTo { index } => {
                                let holder = *texts.get(*index).ok_or(Error(-1))?;
                                nodes.get(*index).ok_or(Error(-1))?.append(holder)?;
                            }
                            Step::Append { parent, child } => {
                                let child = nodes.get(*child).ok_or(Error(-1))?.node();
                                let parent = if *parent == MOUNT {
                                    Node::mount()
                                } else {
                                    nodes.get(*parent).ok_or(Error(-1))?.node()
                                };
                                parent.append(child)?;
                            }
                            Step::SetText { target, text } => {
                                texts.get(*target).ok_or(Error(-1))?.set_text(text)?;
                            }
                            Step::AddListener { target } => {
                                let node = nodes.get(*target).ok_or(Error(-1))?.node();
                                let listener = node.on("click", || {
                                    FIRED.with(|fired| fired.set(fired.get() + 1));
                                })?;
                                LISTENERS.with(|slot| slot.borrow_mut().push(listener));
                            }
                        }
                    }
                    Ok(())
                })
            })
        })
    })
}

/// Write how many handlers ran into the first element, so the arms can be
/// compared after a dispatch storm.
///
/// Without this the storm leaves no trace in the document and two arms that
/// dispatched different numbers of events would still serialise identically.
/// The identity assertion would pass while the event axis measured nothing.
#[unsafe(no_mangle)]
pub extern "C" fn sweep_settle() -> i32 {
    status(TEXTS.with(|texts| {
        let texts = texts.borrow();
        let Some(first) = texts.first() else {
            return Ok(());
        };
        let fired = FIRED.with(Cell::get);
        first.set_text(&format!("fired:{fired}"))
    }))
}

/// The event export. Called by the host once per matched listener.
///
/// The host's contract is that this *completes*: run the handler and drain
/// whatever the guest queued as a result. This guest has no scheduler and no
/// microtask queue, so running the handler is the whole of completing it, and
/// there is nothing to flush. A guest with a reactive core would call its
/// `flush` here.
#[unsafe(no_mangle)]
pub extern "C" fn dispatch(listener_id: u32) -> i32 {
    blitz_wasm_guest::run_listener(listener_id)
}

/// How many handlers have run, for the harness to check the storm landed.
#[unsafe(no_mangle)]
pub extern "C" fn fired_count() -> i32 {
    FIRED.with(Cell::get) as i32
}

/// A status code rather than a trap, all the way out to every export: a trap
/// tears down the instance and takes the reason with it.
fn status(result: Result<(), Error>) -> i32 {
    match result {
        Ok(()) => 0,
        Err(error) => error.code(),
    }
}
